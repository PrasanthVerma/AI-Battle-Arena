// ---------------------------------------------------------------------------
// Retry helper — retries on Mistral / Cohere rate-limit (HTTP 429) errors.
// ---------------------------------------------------------------------------
const isRateLimitError = (err: unknown): boolean => {
  if (!err || typeof err !== "object") return false;
  const e = err as Record<string, unknown>;
  // Mistral SDK surfaces status on the error object
  if (e.status === 429 || e.statusCode === 429) return true;
  // Some SDKs embed it in a nested response
  const body = e.body as Record<string, unknown> | undefined;
  if (body?.code === "1300") return true;
  const msg = String(e.message ?? "");
  return msg.toLowerCase().includes("rate limit") || msg.includes("429");
};

async function withRetry<T>(
  fn: () => Promise<T>,
  maxAttempts = 3,
  baseDelayMs = 2000,
): Promise<T> {
  let attempt = 0;
  while (true) {
    try {
      return await fn();
    } catch (err) {
      attempt++;
      if (!isRateLimitError(err) || attempt >= maxAttempts) throw err;
      const delay = baseDelayMs * Math.pow(2, attempt - 1); // 2s, 4s, 8s …
      console.warn(
        `[Retry] Rate-limit hit, waiting ${delay}ms before attempt ${attempt + 1}/${maxAttempts}…`,
      );
      await new Promise((resolve) => setTimeout(resolve, delay));
    }
  }
}

const solutionNode: GraphNode<typeof State> = async (state) => {
  const prompt =
    state.retrieved_context.length > 0
      ? `
You are answering questions about an uploaded document.

Use ONLY the provided context.

If the answer is not found in the context,
say you could not find enough information.

CONTEXT:
${state.retrieved_context.join("\n\n")}

QUESTION:
${state.problem}
`
      : state.problem;

  state.sendEvent?.("status", "Generating response....");

  let solution1 = "";
  let solution2 = "";
  // Model 1: OpenRouter — wrapped with retry on rate-limit
  const geminiFlashTask = async () => {
    state.sendEvent?.("model_1_start", null);
    const stream = await withRetry(() => openrouterModel.stream(prompt));
    for await (const chunk of stream) {
      const text = typeof chunk.content === "string" ? chunk.content : "";
      solution1 += text;
      state.sendEvent?.("model_1_chunk", text);
    }
  };
  // Model 2: Cohere Command-A — wrapped with retry on rate-limit
  const cohereTask = async () => {
    state.sendEvent?.("model_2_start", null);
    const stream = await withRetry(() => cohereModel.stream(prompt));
    for await (const chunk of stream) {
      const text = typeof chunk.content === "string" ? chunk.content : "";
      solution2 += text;
      state.sendEvent?.("model_2_chunk", text);
    }
  };
  await Promise.all([geminiFlashTask(), cohereTask()]);
  return { solution_1: solution1, solution_2: solution2 };
};

const judgementNode: GraphNode<typeof State> = async (state) => {
  const { problem, solution_1, solution_2 } = state;
  state.sendEvent?.("judge_start", null);

  const structuredGemini = geminiModel.withStructuredOutput(
    z.object({
      solution_1_score: z.number().gte(0).lte(10),

      solution_2_score: z.number().gte(0).lte(10),

      solution_1_reasoning: z.string(),

      solution_2_reasoning: z.string(),
    }),
  );

  const judgeResponse = await structuredGemini.invoke([
    new HumanMessage(`
You are a judge tasked with evaluating two solutions generated by different AI models.

Provide:

- Score out of 10
- Reasoning

Problem:
${problem}

Solution 1:
${solution_1}

Solution 2:
${solution_2}
`),
  ]);

  state.sendEvent?.("judge_result", judgeResponse);

  return {
    judgement: {
      solution_1_score: judgeResponse.solution_1_score,

      solution_2_score: judgeResponse.solution_2_score,

      solution_1_reasoning: judgeResponse.solution_1_reasoning,

      solution_2_reasoning: judgeResponse.solution_2_reasoning,
    },
  };
};

const graph = new StateGraph(State)

  .addNode("file_processing", fileProcessingNode)

  .addNode("chunking", chunkingNode)

  .addNode("embedding", embeddingNode)

  .addNode("retrieval", retrievalNode)

  .addNode("solution", solutionNode)

  .addNode("judgement_node", judgementNode)

  .addConditionalEdges(
    START,
    (state) => {
      if (state.uploaded_file_path) {
        return "rag";
      }

      return "normal";
    },
    {
      rag: "file_processing",
      normal: "solution",
    },
  )

  .addEdge("file_processing", "chunking")

  .addEdge("chunking", "embedding")

  .addEdge("embedding", "retrieval")

  .addEdge("retrieval", "solution")

  .addEdge("solution", "judgement_node")

  .addEdge("judgement_node", END)

  .compile();

export default async function ({
  problem,
  uploaded_file_path,
  sendEvent,
}: {
  problem: string;
  uploaded_file_path?: string;
  sendEvent?: (type: string, data: unknown) => void;
}) {
  const results = await graph.invoke({
    problem,
    uploaded_file_path,
    sendEvent,
  });
  return results;
}
